#!/usr/bin/env node
// Renders COMPATIBILITY.md from the conformance reporter's results (plan MA1 Task 6):
// one row per suite, Mastra version × Loams version × suite → passed, expected failures
// with their issues, and the run.
//
//   node scripts/gen-compat.mjs [resultsDir] [outFile]
//   defaults: test/conformance/results, COMPATIBILITY.md (or `pnpm compat`)

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The Mastra package each suite exercises. */
export const SUITE_PACKAGE = {
  qdrant: '@mastra/qdrant',
  'qdrant-auth': '@mastra/qdrant',
  pg: '@mastra/pg',
  'pg-pooler': '@mastra/pg',
  elasticsearch: '@mastra/elasticsearch',
  examples: '@mastra/core',
};

const SUITE_ORDER = Object.keys(SUITE_PACKAGE);

/** @param {any} r one results/<suite>.json */
function row(r) {
  const pkg = SUITE_PACKAGE[/** @type {keyof typeof SUITE_PACKAGE} */ (r.suite)] ?? '@mastra/core';
  const mastra =
    r.versions?.mastra && r.versions.mastra !== 'unknown' && r.versions.mastra[pkg]
      ? `${pkg} ${r.versions.mastra[pkg]}`
      : `${pkg} (unknown)`;
  const loams = r.versions?.loams ?? 'unknown';
  const passed = `${r.counts.passed}/${r.counts.total - r.counts.skipped}`;
  const issues = [...new Set(r.failures.filter((f) => f.expected && f.issue).map((f) => f.issue))];
  const expected =
    r.counts.expectedFailures === 0
      ? '0'
      : `${r.counts.expectedFailures} (${issues.map((u) => `[#${u.split('/').pop()}](${u})`).join(', ')})`;
  const status = r.ok ? 'OK' : 'FAILED';
  const run = r.run ? `[run](${r.run})` : 'local';
  return `| ${mastra} | ${loams} | ${r.suite} | ${passed} | ${expected} | ${status} | ${run} |`;
}

/** @param {any[]} results @returns {string} */
export function renderCompat(results) {
  const sorted = [...results].sort(
    (a, b) =>
      SUITE_ORDER.indexOf(a.suite) - SUITE_ORDER.indexOf(b.suite) || a.suite.localeCompare(b.suite),
  );
  const lines = [
    '# Compatibility',
    '',
    "Mastra's own adapter test suites, vendored at their release tags, run against Loams by the",
    'conformance gate (`test/conformance`). Every failure is either fixed or listed in',
    '`test/conformance/expected-failures/<suite>.json` with a tracking issue; the gate fails on an',
    'unexpected failure and on an unexpected pass.',
    '',
    'Generated by `pnpm compat` from `test/conformance/results`. Do not edit by hand.',
    '',
    '| Mastra | Loams | Suite | Passed | Expected failures | Gate | Run |',
    '|---|---|---|---|---|---|---|',
  ];
  if (sorted.length === 0) lines.push('| | | No results yet | | | | |');
  for (const r of sorted) lines.push(row(r));
  return `${lines.join('\n')}\n`;
}

/** @param {string} dir */
export function readResults(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
    .filter((r) => r && typeof r.suite === 'string' && r.counts);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const dir = process.argv[2] ?? join(root, 'test', 'conformance', 'results');
  const out = process.argv[3] ?? join(root, 'COMPATIBILITY.md');
  writeFileSync(out, renderCompat(readResults(dir)));
  console.log(`wrote ${out}`);
}
